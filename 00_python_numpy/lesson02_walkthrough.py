"""
第 02 课 · 逐步演示
====================
用只有 5 个点的迷你数据，把训练过程每一步的数字都打印出来。
跑一遍，对照着看，就明白每个变量是什么了。

    python 00_python_numpy/lesson02_walkthrough.py
"""

import numpy as np

# ══════════════════════════════════════════════════════════
# 一、数据是什么
# ══════════════════════════════════════════════════════════
# 我们有 5 个样本。每个样本有一个「输入」和一个「真实答案」：
#
#   样本 1:  x = -2  →  y = -1
#   样本 2:  x = -1  →  y =  1
#   样本 3:  x =  0  →  y =  3
#   样本 4:  x =  1  →  y =  5
#   样本 5:  x =  2  →  y =  7
#
# 这些 y 其实是按 y = 2x + 3 算出来的 —— 但【程序不知道】这个规律，
# 它只能看到上面这 5 对数字，要靠学习把 2 和 3 猜出来。

x = np.array([-2.0, -1.0, 0.0, 1.0, 2.0])   # 5 个样本的输入
y = np.array([-1.0, 1.0, 3.0, 5.0, 7.0])    # 5 个样本的真实答案

print("=" * 62)
print("数据")
print("=" * 62)
print(f"  x = {x}     ← shape {x.shape}，5 个样本的输入")
print(f"  y = {y}      ← shape {y.shape}，5 个样本的真实答案")
print()
print("  目标：找出 w 和 b，使得  y ≈ w * x + b")
print("  真实答案：w = 2, b = 3（程序不知道，要靠学习猜出来）")
print()

# ══════════════════════════════════════════════════════════
# 二、开始训练
# ══════════════════════════════════════════════════════════
w = 0.0          # 初始猜测：瞎猜，从 0 开始
b = 0.0
lr = 0.1         # 学习率：每一步走多大
N = len(y)       # 样本个数 = 5

for step in range(1, 9):
    print("=" * 62)
    print(f"第 {step} 步     当前猜测: w = {w:.4f}, b = {b:.4f}")
    print("=" * 62)

    # ── ① 前向：用当前的 w, b 算预测值 ──
    y_pred = w * x + b
    print(f"  ① 前向  y_pred = {w:.4f} * x + {b:.4f}")
    print(f"                   = {np.round(y_pred, 4)}")

    # ── ② 损失：预测和真实差了多少 ──
    d = y_pred - y                       # 误差：每个样本差多远
    L = np.mean(d ** 2)                  # 均方误差
    print(f"  ② 误差  d = y_pred - y = {np.round(d, 4)}")
    print(f"     损失  L = mean(d²) = {L:.4f}   ← 越小越好")

    # ── ③ 梯度：w 和 b 各该往哪调、调多少 ──
    dw = (2 / N) * np.sum(d * x)         # 每个样本的误差 × 它的 x，求和
    db = (2 / N) * np.sum(d)             # 每个样本的误差，求和
    print(f"  ③ 梯度  dw = (2/{N}) * Σ(d*x) = {dw:+.4f}")
    print(f"          db = (2/{N}) * Σ(d)   = {db:+.4f}")
    print(f"          （正数=该减小它，负数=该增大它）")

    # ── ④ 更新：往梯度的反方向走一小步 ──
    w = w - lr * dw
    b = b - lr * db
    print(f"  ④ 更新  w ← {w + lr*dw:.4f} - 0.1*({dw:+.4f}) = {w:.4f}")
    print(f"          b ← {b + lr*db:.4f} - 0.1*({db:+.4f}) = {b:.4f}")
    print()

# ══════════════════════════════════════════════════════════
# 三、结果
# ══════════════════════════════════════════════════════════
print("=" * 62)
print("训练结束")
print("=" * 62)
print(f"  学到的:  w = {w:.4f},  b = {b:.4f}")
print(f"  真实的:  w = 2.0000,  b = 3.0000")
print()
print(f"  最终预测: {np.round(w * x + b, 4)}")
print(f"  真实答案: {y}")
print(f"  最终损失: {np.mean((w * x + b - y) ** 2):.8f}")
